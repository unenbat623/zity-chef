-- ── Каталогийн буруу зураг болон ангиллыг засах ──────────────────────────────
--
-- Асуудал: `store_products` дээрх зарим мөрийн зураг барааны нэртэйгээ таарахгүй
-- байсан. Хэрэглэгч дэлгүүрт "Гурил" гэж уншаад талхны зураг харж байв.
-- Зургууд нь Chef болон Delguur хоёуланд нь ижил эх сурвалжаас ирдэг тул энд
-- нэг удаа зассанаар хоёулаа зэрэг засагдана.
--
-- Засаж буй зүйлс:
--   • Гурил      → талхны зураг байсан (Талх-тай яг ижил URL хуваалцаж байв)
--   • Байцаа     → брюсселийн байцааны зураг байсан
--   • Гахайн мах → үхрийн махны зураг байсан
--   • Будаа      → ангилал нь '🧂 Амтлагч' байсан (будаа амтлагч биш)
--
-- Талх-ын зураг зөв тул хэвээр үлдээв.

-- Гурил: цагаан гурилын овоо, улаан буудайн түрүүтэй
UPDATE public.store_products
SET image_url = 'https://images.unsplash.com/photo-1627735483792-233bf632619b?w=600&q=80'
WHERE id = '00000000-0000-4000-8000-000000000007';

-- Байцаа: бүтэн ногоон байцаа
